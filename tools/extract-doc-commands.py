#!/usr/bin/env python3
"""Extract the replayable command blocks of docs/building.md into a script (T147, FR-128).

A block is replayable when the fenced code block is immediately preceded (blank lines
allowed) by an HTML comment tag naming the operating systems it applies to::

    <!-- replay:linux -->
    ```bash
    cmake --preset linux-core-release
    ```

Tags: ``linux``, ``windows``, ``macos`` (comma separated, e.g. ``replay:linux,macos``) or
``all``. Linux/macOS blocks must be ``bash``/``sh`` fences, Windows blocks ``powershell``
fences. Blocks are concatenated in document order into one script, so environment
variables exported by an earlier block (``VCPKG_ROOT``) are visible to later ones.

Usage::

    tools/extract-doc-commands.py linux   [--doc docs/building.md] [--output replay.sh]
    tools/extract-doc-commands.py windows [--output replay.ps1]
    tools/extract-doc-commands.py --check         # validate tags/fences of every block
    tools/extract-doc-commands.py linux --list    # show the selected blocks

The generated bash script runs with ``set -euxo pipefail``; the PowerShell script stops on
the first failing command (``$ErrorActionPreference = 'Stop'`` plus an exit-code check after
every native command). ``.github/workflows/docs-build.yml`` runs the scripts on clean
runners.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

KNOWN_OS = ("linux", "windows", "macos")
TAG_RE = re.compile(r"^\s*<!--\s*replay:([a-z,\s]+?)\s*-->\s*$")
FENCE_RE = re.compile(r"^\s*```([A-Za-z0-9_+-]*)\s*$")
SHELL_LANGS = {"linux": {"bash", "sh"}, "macos": {"bash", "sh", "zsh"}, "windows": {"powershell", "pwsh"}}


@dataclass
class Block:
    line: int  # 1-based line of the tag comment
    tags: list[str]
    language: str
    commands: list[str]

    def applies_to(self, target: str) -> bool:
        return "all" in self.tags or target in self.tags


def parse_blocks(text: str, doc_name: str) -> tuple[list[Block], list[str]]:
    """Returns the tagged blocks and a list of problems (empty when the document is valid)."""
    lines = text.splitlines()
    blocks: list[Block] = []
    problems: list[str] = []
    i = 0
    while i < len(lines):
        match = TAG_RE.match(lines[i])
        if not match:
            i += 1
            continue
        tag_line = i + 1
        tags = [t.strip() for t in match.group(1).split(",") if t.strip()]
        unknown = [t for t in tags if t not in KNOWN_OS and t != "all"]
        if unknown:
            problems.append(f"{doc_name}:{tag_line}: unknown replay tag(s) {unknown}")
        # Skip blank lines to the fence.
        j = i + 1
        while j < len(lines) and lines[j].strip() == "":
            j += 1
        fence = FENCE_RE.match(lines[j]) if j < len(lines) else None
        if not fence:
            problems.append(f"{doc_name}:{tag_line}: replay tag is not followed by a fenced code block")
            i += 1
            continue
        language = fence.group(1).lower()
        commands: list[str] = []
        k = j + 1
        while k < len(lines) and not lines[k].strip().startswith("```"):
            commands.append(lines[k])
            k += 1
        if k >= len(lines):
            problems.append(f"{doc_name}:{tag_line}: unterminated code block")
            break
        if "all" in tags:
            # Shared blocks are simple shell lines (cd, npm ...) that PowerShell runs unchanged.
            if language not in {"bash", "sh"}:
                problems.append(
                    f"{doc_name}:{tag_line}: 'all' blocks must be bash/sh fences with commands that "
                    "PowerShell accepts unchanged"
                )
        else:
            for target in [t for t in tags if t in KNOWN_OS]:
                if language not in SHELL_LANGS[target]:
                    problems.append(
                        f"{doc_name}:{tag_line}: block tagged {target} uses a '{language or '(none)'}' "
                        f"fence; expected one of {sorted(SHELL_LANGS[target])}"
                    )
        blocks.append(Block(tag_line, tags, language, commands))
        i = k + 1
    return blocks, problems


def render_bash(blocks: list[Block], doc_name: str, target: str) -> str:
    out = [
        "#!/usr/bin/env bash",
        f"# Generated by tools/extract-doc-commands.py {target} from {doc_name}. Do not edit.",
        "set -euxo pipefail",
        "",
    ]
    for block in blocks:
        out.append(f"# --- {doc_name}:{block.line} (replay:{','.join(block.tags)}) ---")
        out.extend(block.commands)
        out.append("")
    return "\n".join(out)


def ps_quote(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def render_powershell(blocks: list[Block], doc_name: str, target: str) -> str:
    out = [
        f"# Generated by tools/extract-doc-commands.py {target} from {doc_name}. Do not edit.",
        "$ErrorActionPreference = 'Stop'",
        "$PSNativeCommandUseErrorActionPreference = $false",
        "$global:LASTEXITCODE = 0",
        "",
    ]
    for block in blocks:
        out.append(f"# --- {doc_name}:{block.line} (replay:{','.join(block.tags)}) ---")
        for command in block.commands:
            stripped = command.strip()
            if not stripped or stripped.startswith("#"):
                out.append(command)
                continue
            out.append(f"Write-Host ('+ ' + {ps_quote(stripped)})")
            if block.language in ("powershell", "pwsh"):
                out.append(command)
            else:
                # A bash-syntax block tagged for every OS: `cd dir`, `npm ...` and the like are
                # valid PowerShell as long as they stay this simple.
                out.append(command)
            out.append("if ($LASTEXITCODE -ne 0) { Write-Error ('command failed with exit code ' + $LASTEXITCODE); exit $LASTEXITCODE }")
        out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("target", nargs="?", choices=KNOWN_OS, help="operating system to extract for")
    parser.add_argument("--doc", default="docs/building.md", help="markdown document (default: docs/building.md)")
    parser.add_argument("--output", "-o", help="script to write (default: stdout)")
    parser.add_argument("--list", action="store_true", help="list the selected blocks instead of rendering")
    parser.add_argument("--check", action="store_true", help="validate every tagged block and exit")
    args = parser.parse_args(argv)

    repo_root = Path(__file__).resolve().parent.parent
    doc_path = Path(args.doc)
    if not doc_path.is_absolute():
        doc_path = repo_root / doc_path
    if not doc_path.is_file():
        print(f"extract-doc-commands: {doc_path} not found", file=sys.stderr)
        return 2
    doc_name = str(doc_path.relative_to(repo_root)) if doc_path.is_relative_to(repo_root) else str(doc_path)
    blocks, problems = parse_blocks(doc_path.read_text(encoding="utf-8"), doc_name)

    if problems:
        for problem in problems:
            print(problem, file=sys.stderr)
        return 1
    if args.check:
        counts = {os_name: sum(1 for b in blocks if b.applies_to(os_name)) for os_name in KNOWN_OS}
        print(f"{doc_name}: {len(blocks)} tagged blocks (" + ", ".join(f"{k}: {v}" for k, v in counts.items()) + ")")
        return 0
    if not args.target:
        parser.error("target is required unless --check is given")

    selected = [b for b in blocks if b.applies_to(args.target)]
    if not selected:
        print(f"extract-doc-commands: no blocks tagged for {args.target} in {doc_name}", file=sys.stderr)
        return 1
    if args.list:
        for block in selected:
            print(f"{doc_name}:{block.line} replay:{','.join(block.tags)} ({block.language}, {len(block.commands)} lines)")
            for command in block.commands:
                print(f"    {command}")
        return 0

    script = render_powershell(selected, doc_name, args.target) if args.target == "windows" else render_bash(selected, doc_name, args.target)
    if args.output:
        output = Path(args.output)
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(script + "\n", encoding="utf-8", newline="\n")
        if args.target != "windows":
            output.chmod(0o755)
        print(f"extract-doc-commands: wrote {output} ({len(selected)} blocks for {args.target})")
    else:
        sys.stdout.write(script + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
