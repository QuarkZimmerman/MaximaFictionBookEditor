#!/usr/bin/env python3
"""Feature 017 (PD2, DP-2): the single-byte encodings' tables of the TXT export and import.

Reads the WHATWG Encoding Standard's index files kept in third_party/whatwg-encoding/ and writes
core/src/text/single_byte_tables.inc: one row per encoding, its identifier (the Standard's name in
lower case, as the editor names encodings) and the 128 code points of the bytes 0x80-0xFF (0 where
the byte has none). ISO-8859-1, the editor's true Latin-1, is the identity and has no index file.

    python3 tools/encodings/make-tables.py           # rewrite the generated file
    python3 tools/encodings/make-tables.py --check   # compare, offline; exit 1 when stale (CI lint)
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "third_party" / "whatwg-encoding"
TARGET = REPO / "core" / "src" / "text" / "single_byte_tables.inc"

# The order of specs/017-txt-export-import/contracts/encodings.md; ISO-8859-1 last.
ORDER = [
    "ibm866", "iso-8859-2", "iso-8859-3", "iso-8859-4", "iso-8859-5", "iso-8859-6", "iso-8859-7",
    "iso-8859-8", "iso-8859-10", "iso-8859-13", "iso-8859-14", "iso-8859-15", "iso-8859-16",
    "koi8-r", "koi8-u", "macintosh", "windows-874", "windows-1250", "windows-1251", "windows-1252",
    "windows-1253", "windows-1254", "windows-1255", "windows-1256", "windows-1257", "windows-1258",
    "x-mac-cyrillic",
]


def read_index(name: str) -> tuple[list[int], str, str]:
    path = SOURCE / f"index-{name}.txt"
    text = path.read_text(encoding="utf-8")
    high = [0] * 128
    # Lines end with "\n" only: the third column holds the character itself, and splitlines()
    # would also break at U+0085, U+2028 and the like.
    for line in text.split("\n"):
        if not line.strip() or line.startswith("#"):
            continue
        fields = line.split("\t")
        pointer, code_point = int(fields[0].strip()), int(fields[1].strip(), 16)
        if not 0 <= pointer < 128:
            raise SystemExit(f"{path}: pointer {pointer} out of range")
        high[pointer] = code_point
    identifier = re.search(r"# Identifier: ([0-9a-f]+)", text)
    date = re.search(r"# Date: (\S+)", text)
    return high, identifier.group(1) if identifier else "?", date.group(1) if date else "?"


def row(name: str, high: list[int]) -> str:
    lines = [f'    {{"{name}",']
    values = [f"0x{cp:04X}" for cp in high]
    for start in range(0, 128, 8):
        chunk = ", ".join(values[start:start + 8])
        opener = "      {" if start == 0 else "       "
        closer = "}}," if start == 120 else ","
        lines.append(f"{opener}{chunk}{closer}")
    return "\n".join(lines)


def generate() -> str:
    out = [
        "// Generated by tools/encodings/make-tables.py from third_party/whatwg-encoding/ - do not edit.",
        "// The WHATWG Encoding Standard's single-byte index tables (https://encoding.spec.whatwg.org/),",
        "// BSD-3-Clause in source code: third_party/whatwg-encoding/LICENSE.txt. Each row: the encoding's",
        "// identifier and the code points of the bytes 0x80-0xFF (0: the byte has none). Feature 017.",
        "//",
    ]
    rows = []
    for name in ORDER:
        high, identifier, date = read_index(name)
        out.append(f"// index-{name}.txt  {date}  {identifier}")
        rows.append(row(name, high))
    rows.append(row("iso-8859-1", list(range(0x80, 0x100))))
    out.append("// clang-format off")
    out.extend(rows)
    out.append("// clang-format on")
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare only; exit 1 when stale")
    args = parser.parse_args()
    text = generate()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != text:
            print(f"make-tables: {TARGET.relative_to(REPO)} is stale - run tools/encodings/make-tables.py",
                  file=sys.stderr)
            return 1
        print("make-tables: OK")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"make-tables: wrote {TARGET.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
