// The flattened content table of the FB2 2.1 schema (feature 005, the AI assistant - the
// admission check of doc.fragmentFromXml, rpc-api.md §3.2 of the feature; resource-formats.md
// §12 amendment).
//
// Per element declared anywhere in the schema (global or local, named or anonymous type): the
// set of child element names its content model allows - sequences, choices, groups, nested
// particles and `complexContent` extensions flattened, order and multiplicity ignored - and
// whether it may hold character data (a `mixed` complex type, simple content or a simple
// type; an element without a type, FB2's `empty-line`, holds nothing). An element name
// declared several times (`body` as bodyType and notesBodyType) gets the union of its
// declarations. This is the data of the Source view's completion table
// (ui/src/views/source/fb2Elements.json, generated by tools/fb2-schema-elements.py from the
// same files); a Catch2 case pins the two equal, so the XSD stays the one source.
//
// Built from the bundled schema files (validation::schema_dir(): FictionBook.xsd and the
// files it imports) with the hardened parser at first use - never at start-up.
#pragma once

#include <filesystem>
#include <map>
#include <memory>
#include <set>
#include <string>

namespace mfbe::schema {

struct ElementContent {
    std::set<std::string> children;  // local names of the elements the content model allows
    bool text = false;               // character data allowed (mixed or simple content)
};

struct ContentTable {
    std::string root;                                // the one global element: "FictionBook"
    std::map<std::string, ElementContent> elements;  // by local name
    // "" when the table was built; otherwise why not (the schema file that failed and the
    // reason), with `error_path` naming the file.
    std::string error;
    std::string error_path;

    const ElementContent* find(const std::string& name) const;
};

// Builds the table from `main_xsd` and the schema files it imports or includes (relative
// `schemaLocation`, resolved beside it).
ContentTable build_content_table(const std::filesystem::path& main_xsd);

// The table of the validator's schema folder (validation::schema_dir() / FictionBook.xsd),
// built on first use, shared, rebuilt when the folder changes. Thread-safe.
std::shared_ptr<const ContentTable> content_table();

}  // namespace mfbe::schema
