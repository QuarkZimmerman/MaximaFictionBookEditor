/**
 * Feature 020 (T033, US2): Headless Playwright E2E journey for mixed PDFs, strict zero-OCR fast
 * path, editor-only `[data-style="ocr-image"]` Body highlight (with zero `<stylesheet>`), inline
 * cropped illustrations, page-1 cover exclusion, and multilingual `xml:lang`.
 */
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { expect, test } from './fixtures/core';
import { bookXml } from './fixtures/epubImport';
import { importPdfViaMenu, pdf, pdfImportDone } from './fixtures/pdfImport';

const OCR_PDFS = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../../../tests/fixtures/pdf/ocr',
);
const ocrPdf = (name: string): string => path.join(OCR_PDFS, name);

test.describe('US2 (feature 020) - mixed PDFs, zero-OCR fast path, style="ocr-image", crops & xml:lang', () => {
  test.beforeEach(async ({ core, page }) => {
    test.skip(!core.hasCore, 'needs mfbe-core (MFBE_CORE_BIN)');
    await core.openApp(page);
  });

  test('imports mixed-full.pdf with cover exclusion, style="ocr-image" highlight, inline crop, stray furniture, and xml:lang (SC-002)', async ({
    core,
    page,
  }) => {
    const summary = await pdfImportDone(
      page,
      await importPdfViaMenu(core, page, ocrPdf('mixed-full.pdf'), { useOcr: true }),
      90_000,
    );
    const xml = await bookXml(core, page);

    // 1. Page 1 decorative cover stays <coverpage>; cover artwork text NOT in body
    expect(xml).toMatch(/<coverpage>\s*<image l:href="#cover"\/>\s*<\/coverpage>/);
    const bodyMatch = /<body>[\s\S]*<\/body>/.exec(xml);
    expect(bodyMatch).not.toBeNull();
    const bodyXml = bodyMatch![0];
    expect(bodyXml).not.toContain('HARBOUR CHRONICLE');
    expect(bodyXml).not.toContain('COLLECTED EDITION');

    // 2. Verbatim searchable text on pages 2-3 intact
    expect(bodyXml).toContain('verbatim searchable opening paragraph');

    // 3. Embedded text-bearing image on page 3 keeps BOTH <image> AND style="ocr-image" paragraph,
    //    with ZERO <stylesheet> injected into FB2 XML
    expect(xml).not.toContain('<stylesheet');
    expect(bodyXml).toMatch(/<p[^>]*style="ocr-image"[^>]*>[^<]*Western channel lanterns/);
    expect(summary).toContain('Embedded images with text recognized with OCR');

    // 4. Stray-furniture page 4 & inline-illustration page 5 & bilingual page 6
    expect(bodyXml).toContain('watchmaker');
    expect(bodyXml).toContain('timber cottage');
    expect(bodyXml).toContain('northern pavilion');
    expect(bodyXml).toContain('северного порта');
    expect(bodyXml).toMatch(/<(?:p|section)[^>]*xml:lang="ru"/);
    // Ordinary scanned-page paragraphs must NOT receive style="ocr-image"
    expect(bodyXml).not.toMatch(/<p[^>]*style="ocr-image"[^>]*>[^<]*watchmaker/);
    // Kept images: cover + page 3 inset + page 3 pure illustration + page 5 inline crop (>= 4 binaries)
    expect((xml.match(/<binary /g) ?? []).length).toBeGreaterThanOrEqual(4);

    // 5. Editor Body view applies subtle theme-aware highlight on [data-style="ocr-image"]
    const styledPara = page.locator('.fb-editor p[data-style="ocr-image"]').first();
    await expect(styledPara).toBeVisible({ timeout: 15_000 });
    const bg = await styledPara.evaluate(
      (el) => el.ownerDocument.defaultView?.getComputedStyle(el).backgroundColor ?? '',
    );
    expect(bg).not.toBe('rgba(0, 0, 0, 0)');
    expect(bg).not.toBe('transparent');
  });

  test('preserves byte-identical zero-OCR output on pure text, editor-exported, and clean ABBYY PDFs (SC-003)', async ({
    core,
    page,
  }) => {
    // Strip only the per-import fresh <document-info><id> UUID generated by template.xml.
    const stripDocId = (xml: string): string => xml.replace(/<id>[^<]+<\/id>/, '<id>UUID</id>');

    // Pure text PDF: Use OCR on vs off produces identical FB2 XML
    await pdfImportDone(
      page,
      await importPdfViaMenu(core, page, pdf('text-untagged.pdf'), { useOcr: false }),
    );
    const textWithoutOcr = await bookXml(core, page);

    await pdfImportDone(
      page,
      await importPdfViaMenu(core, page, pdf('text-untagged.pdf'), { useOcr: true }),
    );
    const textWithOcr = await bookXml(core, page);
    expect(stripDocId(textWithOcr)).toBe(stripDocId(textWithoutOcr));

    // Editor-exported PDF: Use OCR on vs off produces identical FB2 XML
    await pdfImportDone(
      page,
      await importPdfViaMenu(core, page, pdf('reference-0.0.11-a5.pdf'), { useOcr: false }),
    );
    const ownWithoutOcr = await bookXml(core, page);

    await pdfImportDone(
      page,
      await importPdfViaMenu(core, page, pdf('reference-0.0.11-a5.pdf'), { useOcr: true }),
    );
    const ownWithOcr = await bookXml(core, page);
    expect(stripDocId(ownWithOcr)).toBe(stripDocId(ownWithoutOcr));

    // Clean ABBYY-style pictureWithLayer PDF is NOT re-OCR'd (distinctive spelling preserved)
    await pdfImportDone(
      page,
      await importPdfViaMenu(core, page, ocrPdf('clean-ocr-layer.pdf'), { useOcr: true }),
    );
    const cleanXml = await bookXml(core, page);
    expect(cleanXml).toContain('recognisedlayer');
    expect(cleanXml).not.toContain('recognizedlayer');
  });
});
