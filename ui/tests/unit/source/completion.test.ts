/**
 * Source view tag completion (feature 003 US8, FR-070 to FR-073; T065) on a headless CodeMirror
 * state: the completion source `fb2Completion` - children of the enclosing element after `<`,
 * open elements innermost first after `</`, nothing in comments, processing instructions,
 * CDATA, attribute values or binary placeholders - the generated table against a hand-written
 * reading of the schema, and the keyboard behaviour (Enter and Tab accept, prefix filtering
 * ignores case) through a real `EditorView` in jsdom.
 */

import {
  CompletionContext,
  acceptCompletion,
  completionStatus,
  currentCompletions,
  startCompletion,
  type Completion,
  type CompletionResult,
} from '@codemirror/autocomplete';
import { defaultKeymap, indentWithTab } from '@codemirror/commands';
import { EditorSelection, EditorState, type TransactionSpec } from '@codemirror/state';
import { EditorView, keymap } from '@codemirror/view';

import {
  FB2_ELEMENTS,
  fb2Completion,
  sourceCompletionExtension,
  tagContextAt,
} from '@/views/source/completion';
import { sourceLanguage } from '@/views/source/extensions';

import expectedChildren from './fb2-children.expected.json';

/* ------------------------------------------------------------------------ */
/* Helpers                                                                  */
/* ------------------------------------------------------------------------ */

/** Splits a document with one `|` cursor marker into the text and the cursor offset. */
function cursorDoc(marked: string): { doc: string; pos: number } {
  const pos = marked.indexOf('|');
  if (pos < 0 || marked.indexOf('|', pos + 1) >= 0) throw new Error('exactly one | expected');
  return { doc: marked.slice(0, pos) + marked.slice(pos + 1), pos };
}

function stateOf(doc: string, pos: number, extra: unknown[] = []): EditorState {
  return EditorState.create({
    doc,
    selection: EditorSelection.cursor(pos),
    extensions: [sourceLanguage(), ...(extra as never[])],
  });
}

/** Runs the completion source at the `|` of `marked` (typing-triggered unless `explicit`). */
function complete(marked: string, explicit = false): CompletionResult | null {
  const { doc, pos } = cursorDoc(marked);
  const result = fb2Completion(new CompletionContext(stateOf(doc, pos), pos, explicit));
  if (result instanceof Promise) throw new Error('the source is synchronous');
  return result;
}

const labels = (result: CompletionResult | null): string[] =>
  result ? result.options.map((option) => option.label) : [];

/** Code-point order, the order of the generated table and of the hand-written oracle. */
const sorted = (names: readonly string[]): string[] =>
  [...names].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

const sleep = (ms: number) => new Promise<void>((resolve) => setTimeout(resolve, ms));

const BOOK = `<?xml version="1.0" encoding="utf-8"?>
<FictionBook xmlns="http://www.gribuser.ru/xml/fictionbook/2.0">
  <description>
    <title-info>
      <genre>prose</genre>
      <book-title>Alpha</book-title>
    </title-info>
  </description>
  <body>
    <section id="s1">
      <title><p>One</p></title>
      <p>First <strong>bold</strong> paragraph.</p>
      <poem><stanza><v>line</v></stanza></poem>
      <table><tr><td>cell</td></tr></table>
      <empty-line/>
    </section>
  </body>
  <binary id="cover.jpg" content-type="image/jpeg">\u20261234 bytes\u2026</binary>
</FictionBook>
`;

/** `BOOK` with `insert` placed right before the first occurrence of `anchor`. */
function bookWith(anchor: string, insert: string): string {
  const at = BOOK.indexOf(anchor);
  if (at < 0) throw new Error(`anchor ${anchor} not in BOOK`);
  return BOOK.slice(0, at) + insert + BOOK.slice(at);
}

