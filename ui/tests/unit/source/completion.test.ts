describe('fb2Elements.json (generated by tools/fb2-schema-elements.py)', () => {
  const oracle = Object.fromEntries(
    Object.entries(expectedChildren).filter(([key]) => !key.startsWith('_')),
  ) as Record<string, string[]>;

  it('names the root element and lists every FB2 element with sorted children', () => {
    expect(FB2_ELEMENTS.root).toBe('FictionBook');
    const names = Object.keys(FB2_ELEMENTS.elements);
    expect(names.length).toBeGreaterThanOrEqual(60);
    expect(names).toEqual(sorted(names));
    for (const [name, { children }] of Object.entries(FB2_ELEMENTS.elements)) {
      expect(children, name).toEqual(sorted(children));
      expect(new Set(children).size, `${name}: duplicates`).toBe(children.length);
      for (const child of children) expect(names, `${name} > ${child}`).toContain(child);
    }
    // No element contains the root; the root is offered only at the document level.
    for (const { children } of Object.values(FB2_ELEMENTS.elements)) {
      expect(children).not.toContain('FictionBook');
    }
  });

  it('agrees with the hand-written reading of the schema', () => {
    expect(Object.keys(oracle).length).toBe(11);
    for (const [name, children] of Object.entries(oracle)) {
      expect(FB2_ELEMENTS.elements[name]?.children, name).toEqual(children);
    }
  });

  it('is what the completion offers inside each of those elements', () => {
    const positions: Record<string, string> = {
      FictionBook: bookWith('<description>', '<|'),
      description: bookWith('<title-info>', '<|'),
      'title-info': bookWith('<genre>', '<|'),
      body: bookWith('<section id="s1">', '<|'),
      section: bookWith('<title><p>One', '<|'),
      title: bookWith('<p>One</p>', '<|'),
      p: bookWith('<strong>bold', '<|'),
      poem: bookWith('<stanza>', '<|'),
      stanza: bookWith('<v>line', '<|'),
      table: bookWith('<tr><td>', '<|'),
      binary: bookWith('</binary>', '<|'),
    };
    for (const [name, marked] of Object.entries(positions)) {
      expect(sorted(labels(complete(marked))), name).toEqual(oracle[name]);
    }
  });
});

