describe('tag completion after <', () => {
  it('offers the children of the enclosing element and completes the name only', () => {
    const result = complete(bookWith('<title><p>One', '<sec|'))!;
    expect(labels(result)).toEqual(FB2_ELEMENTS.elements.section!.children);
    // The typed prefix (after the `<`) is what the completion replaces.
    const { doc, pos } = cursorDoc(bookWith('<title><p>One', '<sec|'));
    expect(result.from).toBe(pos - 'sec'.length);
    expect(doc.slice(result.from - 1, result.from)).toBe('<');
    for (const option of result.options) {
      expect(option.apply, option.label).toBe(option.label); // the name, nothing else
    }
  });

  it('offers only p and empty-line inside a title', () => {
    expect(labels(complete(bookWith('<p>One</p>', '<|')))).toEqual(['empty-line', 'p']);
    expect(labels(complete(bookWith('<p>One</p>', '<e|')))).toEqual(['empty-line', 'p']);
  });

  it('offers the inline elements inside a paragraph (mixed content)', () => {
    expect(labels(complete(bookWith('<strong>bold', '<|'))).sort()).toEqual(
      ['a', 'code', 'emphasis', 'image', 'strikethrough', 'strong', 'style', 'sub', 'sup'].sort(),
    );
  });

  it('offers the root element alone at the document level', () => {
    expect(labels(complete('<|'))).toEqual(['FictionBook']);
    expect(labels(complete('<?xml version="1.0"?>\n<Fic|'))).toEqual(['FictionBook']);
    expect(labels(complete(`${BOOK}<|`))).toEqual(['FictionBook']);
  });

  it('offers every element but the root when the enclosing element is unknown', () => {
    const inside = labels(complete('<unknown-element>\n  <|\n</unknown-element>'));
    const all = Object.keys(FB2_ELEMENTS.elements).filter((name) => name !== 'FictionBook');
    expect(sorted(inside)).toEqual(all);
    expect(inside).not.toContain('FictionBook');
  });

  it('offers nothing where the schema allows no element', () => {
    expect(complete(bookWith('</genre>', '<|'))).toBeNull();
    expect(complete(bookWith('</binary>', '<|'))).toBeNull(); // the binary placeholder
    expect(complete(bookWith(' bytes\u2026</binary>', '<|'))).toBeNull(); // inside the placeholder
  });

  it('offers nothing inside comments, processing instructions, CDATA and attribute values', () => {
    expect(complete(bookWith('<body>', '<!-- note <|-->'))).toBeNull();
    expect(complete(bookWith('<body>', '<?pi <| ?>'))).toBeNull();
    expect(complete(bookWith('<body>', '<![CDATA[ <sec| ]]>'))).toBeNull();
    expect(complete('<!DOCTYPE FictionBook <|>\n<FictionBook/>\n')).toBeNull();
    expect(complete(BOOK.replace('id="s1"', 'id="<|"'))).toBeNull();
    // ... and only there: the same positions outside them do offer something.
    expect(complete(bookWith('<body>', '<|'))).not.toBeNull();
  });

  it('offers nothing without a tag start before the cursor, even on demand', () => {
    expect(complete(bookWith('bold', 'bo|'))).toBeNull();
    expect(complete(bookWith('bold', 'bo|'), true)).toBeNull();
    expect(complete(bookWith('<p>First', '<section id="x" |'))).toBeNull(); // attributes: FR-076
    expect(complete(bookWith('<p>First', '<section id="x" |'), true)).toBeNull();
  });

  it('answers the explicit request (hotkey) at a tag start like typing does', () => {
    expect(labels(complete(bookWith('<p>One</p>', '<|'), true))).toEqual(['empty-line', 'p']);
    expect(labels(complete(bookWith('<p>One</p>', '<p|'), true))).toEqual(['empty-line', 'p']);
  });

  it('works on a partially typed tag followed by text (never touching the text after)', () => {
    const result = complete(bookWith('<p>First', '<sec|tion>'))!;
    expect(labels(result)).toContain('section');
    const { pos } = cursorDoc(bookWith('<p>First', '<sec|tion>'));
    expect(result.from).toBe(pos - 3);
    expect(result.to ?? pos).toBe(pos);
  });
});

describe('closing-tag completion after </', () => {
  it('offers exactly the open elements innermost first and inserts the whole closing tag', () => {
    const marked = '<section>\n  <title>\n    <p>One</p>\n    </|\n';
    const result = complete(marked)!;
    expect(labels(result)).toEqual(['title', 'section']);
    const title = result.options[0]!;
    expect(title.boost ?? 0).toBeGreaterThan(result.options[1]!.boost ?? 0);
    // Applying replaces `</` + the typed prefix with the complete closing tag.
    const { doc, pos } = cursorDoc(marked);
    const target = headless(stateOf(doc, pos));
    (title.apply as (view: EditorView, c: Completion, from: number, to: number) => void)(
      target as unknown as EditorView,
      title,
      result.from,
      result.to ?? pos,
    );
    expect(target.state.doc.toString()).toBe(
      '<section>\n  <title>\n    <p>One</p>\n    </title>\n',
    );
    expect(target.state.selection.main.head).toBe(pos - 2 + '</title>'.length);
  });

  it('completes from the typed prefix and keeps the text after the cursor', () => {
    // The `</section>` already in the text closes the title implicitly (MissingCloseTag), so
    // only the section is open at the cursor; the prefix itself is matched by CodeMirror.
    const marked = '<section>\n  <title>\n    <p>One</p>\n    </sec|tion>\n';
    const result = complete(marked)!;
    expect(labels(result)).toEqual(['section']);
    const { doc, pos } = cursorDoc(marked);
    expect(result.from).toBe(pos - 'sec'.length);
    const section = result.options[0]!;
    const target = headless(stateOf(doc, pos));
    (section.apply as (view: EditorView, c: Completion, from: number, to: number) => void)(
      target as unknown as EditorView,
      section,
      result.from,
      pos,
    );
    expect(target.state.doc.toString()).toBe(
      '<section>\n  <title>\n    <p>One</p>\n    </section>tion>\n',
    );
  });

  it('lists every open ancestor of a nested position once, innermost first', () => {
    const marked = bookWith('</v></stanza>', '</|');
    expect(labels(complete(marked))).toEqual([
      'v',
      'stanza',
      'poem',
      'section',
      'body',
      'FictionBook',
    ]);
    const nested = '<section><section><section><p>x</|';
    expect(labels(complete(nested))).toEqual(['p', 'section']);
  });

  it('counts elements with a missing or mismatched closing tag as open', () => {
    // `title` is never closed: `</section>` closes it implicitly (MissingCloseTag).
    expect(labels(complete('<section>\n  <title>\n    <p>One</p>\n    </|\n</section>\n'))).toEqual(
      ['title', 'section'],
    );
    // A stray `</foo>` closes nothing (MismatchedCloseTag).
    expect(labels(complete('<section>\n  <title>text</foo>\n  </|\n</section>\n'))).toEqual([
      'title',
      'section',
    ]);
    // An unclosed `<p>` far above the cursor is still open there (spec scenario 8).
    const unclosed = bookWith('<p>First', '<p>never closed\n      ').replace(
      '<empty-line/>',
      '<empty-line/>\n      </|',
    );
    expect(labels(complete(unclosed))).toEqual(['p', 'section', 'body', 'FictionBook']);
  });

  it('offers nothing when no element is open or inside a comment', () => {
    expect(complete('</|')).toBeNull();
    expect(complete(`${BOOK}</|`)).toBeNull();
    expect(complete(bookWith('<body>', '<!-- </| -->'))).toBeNull();
  });
});

describe('tagContextAt', () => {
  it('reports the kind, prefix and enclosing element', () => {
    const open = cursorDoc(bookWith('<title><p>One', '<sec|'));
    expect(tagContextAt(stateOf(open.doc, open.pos), open.pos)).toMatchObject({
      kind: 'open',
      prefix: 'sec',
      enclosing: 'section',
    });
    const close = cursorDoc(bookWith('<title><p>One', '</t|'));
    expect(tagContextAt(stateOf(close.doc, close.pos), close.pos)).toMatchObject({
      kind: 'close',
      prefix: 't',
      open: ['section', 'body', 'FictionBook'],
    });
    const text = cursorDoc(bookWith('bold', 'bo|'));
    expect(tagContextAt(stateOf(text.doc, text.pos), text.pos)).toBeNull();
  });
});

