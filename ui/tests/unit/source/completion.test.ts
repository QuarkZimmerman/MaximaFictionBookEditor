/** Dispatch target over a headless state (what the controller uses while unmounted). */
function headless(initial: EditorState): {
  state: EditorState;
  dispatch(spec: TransactionSpec): void;
} {
  const target = {
    current: initial,
    get state() {
      return target.current;
    },
    dispatch(spec: TransactionSpec) {
      target.current = target.current.update(spec).state;
    },
  };
  return target;
}

describe('completion in an editor view', () => {
  beforeAll(() => {
    // jsdom has no layout: CodeMirror's measuring needs these to exist.
    Object.defineProperty(Range.prototype, 'getClientRects', {
      configurable: true,
      value: () => ({ length: 0, item: () => null, [Symbol.iterator]: function* () {} }),
    });
    Object.defineProperty(Range.prototype, 'getBoundingClientRect', {
      configurable: true,
      value: () => ({ x: 0, y: 0, top: 0, left: 0, right: 0, bottom: 0, width: 0, height: 0 }),
    });
  });

  function editor(marked: string, on = true): EditorView {
    const { doc, pos } = cursorDoc(marked);
    return new EditorView({
      state: stateOf(doc, pos, [
        sourceCompletionExtension(on),
        keymap.of([...defaultKeymap, indentWithTab]),
      ]),
      parent: document.body,
    });
  }

  /** Opens the list on demand and waits until the options are there (past the interaction delay). */
  async function open(view: EditorView): Promise<string[]> {
    expect(startCompletion(view)).toBe(true);
    for (let i = 0; i < 40 && completionStatus(view.state) !== 'active'; i += 1) await sleep(10);
    expect(completionStatus(view.state)).toBe('active');
    await sleep(100); // acceptCompletion ignores keys pressed right after the list opened
    return currentCompletions(view.state).map((c) => c.label);
  }

  function press(view: EditorView, key: string, keyCode: number): void {
    view.contentDOM.dispatchEvent(
      new KeyboardEvent('keydown', { key, code: key, keyCode, bubbles: true, cancelable: true }),
    );
  }

  it('filters case-insensitively by the typed prefix and inserts the schema spelling', async () => {
    const view = editor(bookWith('<title><p>One', '<SEC|'));
    try {
      expect(await open(view)).toEqual(['section']);
      expect(acceptCompletion(view)).toBe(true);
      expect(view.state.doc.toString()).toContain('<section<title><p>One');
      expect(completionStatus(view.state)).toBeNull();
    } finally {
      view.destroy();
    }
  });

  it('accepts with Tab like with Enter, and both keys work as before otherwise', async () => {
    const view = editor(bookWith('<title><p>One', '<ti|'));
    try {
      expect(await open(view)).toEqual(['title']);
      press(view, 'Tab', 9);
      expect(view.state.doc.toString()).toContain('<title<title><p>One');
      expect(completionStatus(view.state)).toBeNull();
      // No list: Tab indents, Enter breaks the line.
      const before = view.state.doc.toString();
      press(view, 'Tab', 9);
      expect(view.state.doc.toString()).not.toBe(before);
      expect(view.state.doc.lines).toBe(EditorState.create({ doc: before }).doc.lines);
      press(view, 'Enter', 13);
      expect(view.state.doc.lines).toBe(EditorState.create({ doc: before }).doc.lines + 1);
    } finally {
      view.destroy();
    }
  });

  it('accepts a closing tag with Enter and dismisses the list with Escape', async () => {
    const view = editor('<section>\n  <title>\n    <p>One</p>\n    </|\n');
    try {
      expect(await open(view)).toEqual(['title', 'section']);
      press(view, 'Escape', 27);
      expect(completionStatus(view.state)).toBeNull();
      expect(view.state.doc.toString()).toBe('<section>\n  <title>\n    <p>One</p>\n    </\n');
      expect(await open(view)).toEqual(['title', 'section']);
      press(view, 'Enter', 13);
      expect(view.state.doc.toString()).toBe(
        '<section>\n  <title>\n    <p>One</p>\n    </title>\n',
      );
    } finally {
      view.destroy();
    }
  });

  it('does nothing when the setting is off', async () => {
    const view = editor(bookWith('<title><p>One', '<sec|'), false);
    try {
      expect(startCompletion(view)).toBe(false);
      await sleep(150);
      expect(completionStatus(view.state)).toBeNull();
      expect(document.querySelector('.cm-tooltip-autocomplete')).toBeNull();
    } finally {
      view.destroy();
    }
  });
});
