export default async function run(ctx) {
  const Ts = new Date().getTime();
  re = [];
  re_ = [];
  stroka_v_statistike = [];
  count = [];
  for (k = 0; k <= 999; k++) count[k] = 0; // Обнуление всех возможных счетчиков
  count_P = 0;
  count_GU = 0;
  nachalo = true;

  const snapshot = await mfbe.doc.get();
  const paragraphs = paragraphsOf(snapshot, { history: ObrabotkaHistory_on_off != 0, annotation: ObrabotkaAnnotation_on_off != 0 });
  let descriptionChanged = false;
  for (let i = 0; i < paragraphs.length; i += 1) {
    const paragraph = paragraphs[i];
    const extras = [];
    const before = serializeInline(paragraph.node.content, extras);
    s = before; //  Получение текста параграфа (с внутренними тегами).
    count_P++; // Счетчик строк.
    ({ title, history, stanza, poem, epigraph, annotation, cite, table, subtitle, text_author, text } = paragraph.flags);
    Opertiones(); //  Выполнение пользовательских операций
    nachalo = false;
    if (s !== before) {
      //  Если строка изменилась... увеличиваем счетчик изменений строк и сохраняем измененную строку.
      count_GU++;
      const content = parseInline(s, extras);
      const source = paragraph.source;
      if (paragraph.description) {
        if (source.type === 'empty-line') source.type = 'p';
        source.content = content;
        descriptionChanged = true;
      } else {
        const type = source.type === 'empty-line' ? 'p' : source.type;
        await mfbe.doc.replaceNode(source.attrs.nodeId, { type, attrs: { ...source.attrs }, content });
      }
    }
    if (i % 200 === 0) await mfbe.ui.progress(i, paragraphs.length, ctx.script.name);
    if (ctx.cancelled) return;
  }
  if (descriptionChanged) await mfbe.doc.setDescription(snapshot.description);

  await showStatistics(ctx, {
    name: ScriptName,
    version: NumerusVersion,
    height: Vysota_teksta,
    all: VseStroki_on_off,
    started: Ts,
    count_P,
    count_GU,
    count,
    stroka: stroka_v_statistike,
    re_,
  });
}

